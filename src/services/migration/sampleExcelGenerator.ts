  /**
   * Generates a multi-sheet XLSX Workbook
   */
  static generateSampleWorkbook(): Uint8Array {
    const wb = XLSX.utils.book_new();

    // Sheet 1: Members (لیست اعضای باشگاه)
    const membersData = this.getSampleRecords();
    const wsMembers = XLSX.utils.json_to_sheet(membersData);
    
    // Set column widths
    wsMembers['!cols'] = [
      { wch: 14 }, // شماره عضویت
      { wch: 22 }, // نام و نام خانوادگی
      { wch: 15 }, // کد ملی
      { wch: 16 }, // شماره موبایل
      { wch: 18 }, // مبلغ بدهی
      { wch: 14 }, // تاریخ ثبت‌نام
      { wch: 14 }, // تاریخ انقضا
      { wch: 12 }, // وضعیت
      { wch: 16 }, // کارت تردد
      { wch: 16 }, // شماره اضطراری
      { wch: 22 }, // رشته ورزشی
      { wch: 35 }, // یادداشت
    ];

    XLSX.utils.book_append_sheet(wb, wsMembers, 'لیست اعضای باشگاه');

    // Sheet 2: Field Guide (راهنمای ستون‌ها)
    const guideData = this.getFieldGuideRecords();
    const wsGuide = XLSX.utils.json_to_sheet(guideData);
    wsGuide['!cols'] = [
      { wch: 20 },
      { wch: 25 },
      { wch: 28 },
      { wch: 60 },
    ];
    XLSX.utils.book_append_sheet(wb, wsGuide, 'راهنمای ستون‌ها');

    // Write binary ArrayBuffer
    const wbout = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
    return new Uint8Array(wbout);
  }

  /**
   * Browser-side trigger to download sample .xlsx
   */
  static downloadSampleExcel(filename = 'gym_members_sample.xlsx') {
    try {
      const data = this.generateSampleWorkbook();
      const blob = new Blob([data], { 
        type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' 
      });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = filename;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (err) {
      console.error('Failed to download sample Excel file:', err);
      alert('خطا در دانلود فایل نمونه اکسل: ' + (err as Error).message);
    }
  }
